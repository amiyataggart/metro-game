#!/usr/bin/env node
/* eslint-disable no-console */
/*
 * Compares the curated service tables (src/app/(game)/london/services/*.ts)
 * with current features.json line membership and prints a Markdown report:
 *   - per-line summary: stations kept / to add / to remove
 *   - per line: stations in the tables but not in features.json for that line
 *     (to add) and in features.json but not in the tables (to remove / out of scope)
 *   - stations new to the game entirely
 *   - stops whose inclusion rests on knowledge only (from the
 *     `// knowledge-only stops:` / `// source: knowledge` comments)
 *   - END_STATIONS sanity check (every end station appears on its line)
 *
 *   node scripts/report-service-diff.js > docs/superpowers/specs/2026-10-12-service-diff.md
 *
 * Read-only: never writes to features.json or routes*.json.
 */
const fs = require('fs')
const path = require('path')
const ts = require('typescript')

const ROOT = path.join(__dirname, '..')
const LONDON = path.join(ROOT, 'src', 'app', '(game)', 'london')
const SERVICES_DIR = path.join(LONDON, 'services')

// Minimal TS loader: transpile .ts to CommonJS on require.
require.extensions['.ts'] = (module, filename) => {
  const src = fs.readFileSync(filename, 'utf8')
  const out = ts.transpileModule(src, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019, esModuleInterop: true },
    fileName: filename,
  }).outputText
  module._compile(out, filename)
}

const { SERVICES_BY_LINE } = require(path.join(SERVICES_DIR, 'index.ts'))
const { END_STATIONS, FULL_LINES } = require(path.join(LONDON, 'scope.ts'))
const features = JSON.parse(fs.readFileSync(path.join(LONDON, 'data', 'features.json'), 'utf8')).features

const featByLine = new Map()
const allFeatureNames = new Set()
for (const f of features) {
  const { line, name } = f.properties
  if (!featByLine.has(line)) featByLine.set(line, new Set())
  featByLine.get(line).add(name)
  allFeatureNames.add(name)
}

const tableByLine = new Map()
for (const [line, svcs] of Object.entries(SERVICES_BY_LINE)) {
  const set = new Set()
  for (const s of svcs) {
    if (s.line !== line) throw new Error(`service "${s.name}" in ${line}.ts has line=${s.line}`)
    for (const st of s.stops) set.add(st)
  }
  tableByLine.set(line, set)
}

// Knowledge-only stops, read from the source comments.
function knowledgeStops(line) {
  const src = fs.readFileSync(path.join(SERVICES_DIR, `${line}.ts`), 'utf8').split('\n')
  const out = []
  for (let i = 0; i < src.length; i++) {
    const kn = src[i].match(/^\s*\/\/ knowledge-only stops: (.*)$/)
    const whole = /^\s*\/\/ source: knowledge/.test(src[i])
    if (!kn && !whole) continue
    let j = i
    while (j < src.length && !/name: '/.test(src[j])) j++
    const svc = (src[j] || '').match(/name: '(.*)',/)
    const name = svc ? svc[1].replace(/\\'/g, "'") : '?'
    if (kn) out.push({ service: name, stops: kn[1].split(', '), whole: false })
    else {
      const svcObj = SERVICES_BY_LINE[line].find((s) => s.name === name)
      out.push({ service: name, stops: svcObj ? svcObj.stops : [], whole: true })
    }
  }
  return out
}

const sorted = (it) => [...it].sort((a, b) => a.localeCompare(b))
const lines = sorted(new Set([...featByLine.keys(), ...tableByLine.keys()]))
const L = []
const p = (s = '') => L.push(s)

p('# Service tables vs features.json — diff report')
p()
p(`_Generated by \`node scripts/report-service-diff.js\` on ${new Date().toISOString().slice(0, 10)}. ` +
  'Tables: `src/app/(game)/london/services/*.ts`; scope: `src/app/(game)/london/scope.ts`. ' +
  'Draft for user review (Task 6) — nothing here has been applied to features.json / routes.json._')
p()
p('## Summary')
p()
p('| Line | Scope | Services | In tables | Kept | To add | To remove |')
p('|---|---|---:|---:|---:|---:|---:|')
let tAdd = 0, tRem = 0, tKeep = 0
const perLine = []
for (const line of lines) {
  const feat = featByLine.get(line) || new Set()
  const tab = tableByLine.get(line) || new Set()
  const add = sorted([...tab].filter((n) => !feat.has(n)))
  const rem = sorted([...feat].filter((n) => !tab.has(n)))
  const keep = [...tab].filter((n) => feat.has(n)).length
  tAdd += add.length; tRem += rem.length; tKeep += keep
  perLine.push({ line, add, rem })
  const scope = FULL_LINES.has(line) ? 'full' : END_STATIONS[line] ? 'trimmed' : '—'
  const nsvc = (SERVICES_BY_LINE[line] || []).length
  p(`| ${line}${featByLine.has(line) ? '' : ' (new line)'} | ${scope} | ${nsvc} | ${tab.size} | ${keep} | ${add.length} | ${rem.length} |`)
}
p(`| **Total** | | | | **${tKeep}** | **${tAdd}** | **${tRem}** |`)
p()
p('“To add” = (station, line) pairs in the tables but not in features.json; “To remove” = pairs in features.json not served by any in-scope table entry (out of scope, or not called at by the current timetable).')
p()

const newStations = sorted(new Set([...tableByLine.values()].flatMap((s) => [...s]).filter((n) => !allFeatureNames.has(n))))
p(`## Stations new to the game (${newStations.length})`)
p()
p('Not in features.json under any name; table entries use the official National Rail name. Each needs coordinates from an OSM station node when features.json is rebuilt.')
p()
for (const n of newStations) {
  const on = sorted([...tableByLine.entries()].filter(([, s]) => s.has(n)).map(([l]) => l))
  p(`- ${n} — ${on.join(', ')}`)
}
p()

p('## Per-line changes')
p()
for (const { line, add, rem } of perLine) {
  if (!add.length && !rem.length) continue
  p(`### ${line}`)
  p()
  if (add.length) p(`**To add (${add.length}):** ${add.join('; ')}`)
  if (add.length) p()
  if (rem.length) p(`**To remove (${rem.length}):** ${rem.join('; ')}`)
  if (rem.length) p()
}
const unchanged = perLine.filter((x) => !x.add.length && !x.rem.length).map((x) => x.line)
p(`Unchanged lines: ${unchanged.join(', ') || 'none'}.`)
p()

p('## Knowledge-only stops (no OSM route relation lists them)')
p()
p('Every other stop in the tables appears in at least one cited OSM route relation (see the `// source: osm relation …` comment above each service).')
p()
for (const line of sorted(tableByLine.keys())) {
  const k = knowledgeStops(line)
  if (!k.length) continue
  p(`**${line}**`)
  p()
  for (const e of k) p(`- ${e.service}${e.whole ? ' — whole service (no OSM relation)' : ''}: ${e.stops.join(', ')}`)
  p()
}

p('## Full-line stops taken from features.json (OSM relations omit them)')
p()
p('Full lines keep their audited features.json membership; these stops are missing from every OSM relation of the line and were placed at the best-fitting position.')
p()
for (const line of sorted(tableByLine.keys())) {
  const src = fs.readFileSync(path.join(SERVICES_DIR, `${line}.ts`), 'utf8')
  for (const m of src.matchAll(/\/\/ from features\.json membership \(OSM relation omits them\): (.*)/g)) p(`- ${line}: ${m[1]}`)
}
p()

p('## END_STATIONS check')
p()
const bad = []
for (const [line, ends] of Object.entries(END_STATIONS)) {
  const tab = tableByLine.get(line) || new Set()
  for (const e of ends) if (!tab.has(e)) bad.push(`${line}: ${e}`)
}
p(bad.length ? `End stations not served by their line's tables: ${bad.join('; ')}` : 'Every END_STATIONS entry is served by its line\'s tables.')
p()

// Hand-written reviewer notes live in their own file so re-running this
// script never wipes them; they are appended verbatim (minus their H1).
const NOTES = path.join(ROOT, 'docs', 'superpowers', 'specs', '2026-10-12-service-diff-notes.md')
if (fs.existsSync(NOTES)) {
  p('---')
  p()
  p('## Reviewer notes')
  p()
  p('_Hand-written; source: `docs/superpowers/specs/2026-10-12-service-diff-notes.md` (edit there, not here)._')
  p()
  p(fs.readFileSync(NOTES, 'utf8').replace(/^# .*\n+/, '').replace(/^_Maintained by hand[^\n]*\n+/, '').trimEnd())
  p()
}

process.stdout.write(L.join('\n'))
